"""Build a herbing / mining path module from a .gatherprofile (XML) file.

Usage: python -I tools/build_gather_path.py <profile.gatherprofile> <id> [<label>]

Writes grind/paths/gather/<id>.lua and (re)writes grind/paths/gather/catalog.lua
with one entry per module found in that folder.

The profile's <Mesh> is the recorded walk (points ~7 yd apart) and is what the
path is built from; <Hotspots> (the coarse loop) is kept in the module for
reference. A .gatherprofile carries no heights: z is written as 0 and the path
is flagged no_z = true - grind/engine walks such a path with the player's
height and MasterArthasNav finds the ground (it never follow_paths the z = 0
points). Junk rows are dropped: continentid 0 separators, rows on another
continent than the path's, consecutive duplicates; only the longest run between
junk rows is kept.
"""
import math
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(ROOT, "grind", "paths", "gather")
PAT = re.compile(r'<waypoint x="(-?[\d.]+)" y="(-?[\d.]+)" continentid="(\d+)"')


def section(src, tag):
    a, b = src.find("<%s>" % tag), src.find("</%s>" % tag)
    return src[a:b] if a >= 0 and b > a else ""


def points(text):
    return [(float(x), float(y), int(c)) for x, y, c in PAT.findall(text)]


def clean(rows, continent):
    # the rows between junk rows (separators / other continents) are runs;
    # the longest run is the recorded walk, the rest are recorder leftovers
    runs, cur = [], []
    for x, y, c in rows:
        if c != continent:
            if cur:
                runs.append(cur)
            cur = []
            continue
        if cur and abs(cur[-1][0] - x) < 0.01 and abs(cur[-1][1] - y) < 0.01:
            continue
        cur.append((x, y))
    if cur:
        runs.append(cur)
    out = max(runs, key=len) if runs else []
    # a recorder spike: a point far from both neighbours
    keep = []
    for i, p in enumerate(out):
        if 0 < i < len(out) - 1:
            a, b = out[i - 1], out[i + 1]
            if math.dist(a, p) > 60 and math.dist(p, b) > 60 and math.dist(a, b) < 60:
                continue
        keep.append(p)
    return keep


def num(v):
    s = ("%.2f" % v).rstrip("0").rstrip(".")
    return s if s not in ("-0", "") else "0"


def write_module(pid, label, src_name, continent, mesh, hot, faction, pull):
    gaps = [math.dist(mesh[i], mesh[i + 1]) for i in range(len(mesh) - 1)]
    close = math.dist(mesh[0], mesh[-1])
    lines = []
    lines.append("-- " + "=" * 76)
    lines.append("-- Master Farmer - Grindbot")
    lines.append("-- %s (herbing + mining path)" % label)
    lines.append("-- " + "=" * 76)
    lines.append("-- Authors: BLIZZ - Anthonyk")
    lines.append("-- Version: 3.9.1")
    lines.append("-- Folder: Master_Farmer_Grindbot")
    lines.append("-- " + "=" * 76)
    lines.append("-- Generated by tools/build_gather_path.py. Do not hand-edit: regenerate instead.")
    lines.append("--   source file   : %s" % src_name)
    lines.append("--   continent id  : %d" % continent)
    lines.append("--   waypoints     : %d (the profile's Mesh, cleaned)" % len(mesh))
    lines.append("--   spacing       : %.1f yd average, %.1f yd longest" % (sum(gaps) / len(gaps), max(gaps)))
    lines.append("--   first/last gap: %.1f yd" % close)
    lines.append("--   hotspots      : %d (the profile's coarse loop, reference only)" % len(hot))
    lines.append("-- The profile has no heights: z = 0, no_z = true (walked at the player's")
    lines.append("-- height, MasterArthasNav finds the ground).")
    lines.append("-- " + "=" * 76)
    lines.append("return {")
    lines.append('    id = "%s",' % pid)
    lines.append('    name = "%s",' % label)
    lines.append("    map_id = 0,")
    lines.append("    continent_id = %d," % continent)
    lines.append("    loop = true,")
    lines.append('    region = "gather",')
    lines.append('    source = "gather",')
    lines.append('    kind = "gather",')
    lines.append('    faction = "%s",' % faction)
    lines.append("    pull = %d," % pull)
    lines.append("    gather = true,")
    lines.append("    no_z = true,")
    lines.append("    coords = {")
    row = []
    for x, y in mesh:
        row.append("%s, %s, 0" % (num(x), num(y)))
        if len(row) == 4:
            lines.append("        " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("        " + ", ".join(row) + ",")
    lines.append("    },")
    lines.append("    hotspots = {")
    row = []
    for x, y in hot:
        row.append("%s, %s" % (num(x), num(y)))
        if len(row) == 6:
            lines.append("        " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("        " + ", ".join(row) + ",")
    lines.append("    },")
    lines.append("}")
    os.makedirs(OUT_DIR, exist_ok=True)
    with open(os.path.join(OUT_DIR, pid + ".lua"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    return len(mesh)


def write_catalog():
    entries = []
    for fn in sorted(os.listdir(OUT_DIR)):
        if not fn.endswith(".lua") or fn == "catalog.lua":
            continue
        s = open(os.path.join(OUT_DIR, fn), encoding="utf-8").read()
        get = lambda k: re.search(r'^\s*%s = "?([^",]*)"?,' % k, s, re.M).group(1)
        count = len(re.findall(r"-?[\d.]+, -?[\d.]+, 0", s.split("coords = {")[1].split("},")[0]))
        entries.append((get("id"), get("name"), get("faction"), int(get("pull")), count))
    lines = []
    lines.append("-- " + "=" * 76)
    lines.append("-- Master Farmer - Grindbot")
    lines.append("-- Herbing + mining paths - path index")
    lines.append("-- " + "=" * 76)
    lines.append("-- Authors: BLIZZ - Anthonyk")
    lines.append("-- Version: 3.9.1")
    lines.append("-- Folder: Master_Farmer_Grindbot")
    lines.append("-- " + "=" * 76)
    lines.append("-- Index only (modules load on demand, path_format.take_module).")
    lines.append("-- Generated by tools/build_gather_path.py. Do not hand-edit: regenerate instead.")
    lines.append("-- " + "=" * 76)
    lines.append("return {")
    for pid, name, faction, pull, count in entries:
        lines.append("    {")
        lines.append('        id = "%s",' % pid)
        lines.append('        label = "%s",' % name)
        lines.append('        module = "grind/paths/gather/%s",' % pid)
        lines.append('        region = "gather",')
        lines.append('        source = "gather",')
        lines.append('        kind = "gather",')
        lines.append('        faction = "%s",' % faction)
        lines.append("        map_id = 0,")
        lines.append("        count = %d," % count)
        lines.append("        pull = %d," % pull)
        lines.append("        loop = true,")
        lines.append("    },")
    lines.append("}")
    with open(os.path.join(OUT_DIR, "catalog.lua"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    return len(entries)


def main():
    src_path, pid = sys.argv[1], sys.argv[2]
    label = sys.argv[3] if len(sys.argv) > 3 else pid
    src = open(src_path, encoding="utf-8-sig").read()
    raw_mesh = points(section(src, "Mesh"))
    raw_hot = points(section(src, "Hotspots"))
    conts = {}
    for _, _, c in raw_mesh + raw_hot:
        if c:
            conts[c] = conts.get(c, 0) + 1
    continent = max(conts, key=conts.get)
    mesh = clean(raw_mesh, continent)
    hot = clean(raw_hot, continent)
    fac = re.search(r"<Faction>([^<]*)</Faction>", src)
    faction = (fac.group(1).strip().lower() if fac else "both") or "both"
    pr = re.search(r"<Pullrange>(\d+)</Pullrange>", src)
    pull = int(pr.group(1)) if pr else 20
    n = write_module(pid, label, os.path.basename(src_path), continent, mesh, hot, faction, pull)
    c = write_catalog()
    print("%s: %d waypoints (mesh rows %d), %d hotspots, continent %d, faction %s; catalog %d entries"
          % (pid, n, len(raw_mesh), len(hot), continent, faction, c))


if __name__ == "__main__":
    main()
